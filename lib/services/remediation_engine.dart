import '../models/models.dart';

/// Remediation Plan Generator.
///
/// Produces a prioritized, concrete action plan from audit findings.
/// Rules are deterministic and explainable: every step maps to at least
/// one observed exposure (breached data class, pwned password, or a
/// discovered public account cluster).
class RemediationEngine {
  const RemediationEngine();

  List<RemediationStep> buildPlan({
    required List<Breach> breaches,
    required List<PlatformHit> platformHits,
    required PwnedPasswordResult? passwordResult,
    required RiskAssessment risk,
    required InputKind inputKind,
  }) {
    final steps = <RemediationStep>[];
    final exposedTypes = <String>{};
    for (final b in breaches) {
      exposedTypes.addAll(b.dataClasses);
    }
    final foundPlatforms = platformHits.where((h) => h.found).toList();
    final passwordBreaches =
        breaches.where((b) => b.dataClasses.contains('Passwords')).toList();

    // 1 — Pwned / breached passwords: the #1 account-takeover vector.
    if (passwordResult != null && passwordResult.found) {
      steps.add(RemediationStep(
        priority: RemediationPriority.critical,
        iconKey: 'key',
        effortMinutes: 15,
        titleEn: 'Replace the compromised password everywhere',
        titleAr: 'استبدل كلمة المرور المُخترقة في كل مكان',
        bodyEn:
            'The checked password has appeared ${passwordResult.count} times in known breach corpora and is in every credential-stuffing wordlist. Replace it on every account that uses it (or a variant of it) with a unique 16+ character passphrase generated by a password manager.',
        bodyAr:
            'ظهرت كلمة المرور التي فحصتها ${passwordResult.count} مرة في قواعد بيانات التسريبات المعروفة، وهي موجودة في جميع قوائم هجمات حشو الاعتماد. استبدلها في كل حساب يستخدمها (أو أي صيغة قريبة منها) بعبارة مرور فريدة من 16 حرفًا على الأقل يتم إنشاؤها عبر مدير كلمات مرور.',
      ));
    }
    if (passwordBreaches.isNotEmpty) {
      final names = passwordBreaches.map((b) => b.title).take(3).join(', ');
      steps.add(RemediationStep(
        priority: RemediationPriority.critical,
        iconKey: 'refresh',
        effortMinutes: 20,
        titleEn:
            'Rotate passwords on ${passwordBreaches.length} breached site(s)',
        titleAr:
            'بدّل كلمات المرور في ${passwordBreaches.length} موقع مُخترق',
        bodyEn:
            'Passwords were exposed in: $names. Change those passwords first, then audit every other account sharing the same password. Assume the old credentials are public and are being tried against your email, banking and social accounts right now (credential stuffing).',
        bodyAr:
            'تم تسريب كلمات مرور من: $names. غيّر كلمات المرور تلك أولًا، ثم افحص أي حساب آخر يستخدم نفس كلمة المرور. افترض أن بيانات الاعتماد القديمة أصبحت علنية ويتم تجربتها الآن ضد بريدك وحساباتك البنكية والاجتماعية (هجمات حشو الاعتماد).',
      ));
    }

    // 2 — Financial data.
    if (exposedTypes.contains('Credit cards') ||
        exposedTypes.contains('Bank account numbers')) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.critical,
        iconKey: 'creditCard',
        effortMinutes: 30,
        titleEn: 'Freeze and reissue exposed payment cards',
        titleAr: 'جمّد البطاقات البنكية المُعرّضة وأعد إصدارها',
        bodyEn:
            'Payment data appears in your breach history. Contact your bank, freeze the affected card(s), request reissue with a new number, enable per-transaction alerts, and review the last 12 months of statements for small "test" charges.',
        bodyAr:
            'تظهر بيانات دفع في سجل التسريبات الخاص بك. تواصل مع البنك، جمّد البطاقات المتأثرة، اطلب إصدار بطاقة برقم جديد، فعّل تنبيهات المعاملات، وراجع كشوف آخر 12 شهرًا بحثًا عن عمليات صغيرة تجريبية.',
      ));
    }

    // 3 — Government IDs.
    if (exposedTypes.contains('Social security numbers') ||
        exposedTypes.contains('Government issued IDs') ||
        exposedTypes.contains('Passport numbers')) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.critical,
        iconKey: 'shield',
        effortMinutes: 45,
        titleEn: 'Place a fraud alert / credit freeze for exposed ID numbers',
        titleAr: 'فعّل تنبيه الاحتيال / تجميد الائتمان لأرقام الهوية المُسربة',
        bodyEn:
            'Government ID data enables full identity theft (loans, SIM registration, account recovery). Place a credit freeze or fraud alert with the relevant bureaus/authorities, and treat any "bank" or "government" call that quotes your ID number as untrusted — call back on the official number.',
        bodyAr:
            'بيانات الهوية الحكومية تتيح سرقة هوية كاملة (قروض، تسجيل شرائح اتصال، استرجاع حسابات). فعّل تجميد الائتمان أو تنبيه الاحتيال لدى الجهات المختصة، وعامل أي اتصال من "بنك" أو "جهة حكومية" يذكر رقم هويتك على أنه غير موثوق — اتصل أنت بالرقم الرسمي.',
      ));
    }

    // 4 — 2FA when anything meaningful is exposed.
    if (breaches.isNotEmpty || (passwordResult?.found ?? false)) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.high,
        iconKey: 'smartphone',
        effortMinutes: 25,
        titleEn: 'Enable 2FA via Authenticator App (not SMS)',
        titleAr: 'فعّل المصادقة الثنائية عبر تطبيق المصادقة (وليس SMS)',
        bodyEn:
            'With breached credentials in circulation, a password alone is not protection. Enable TOTP authenticator-app 2FA (or a hardware security key / passkey) starting with: email, banking, cloud storage, then social accounts. Avoid SMS codes where an authenticator option exists — SIM-swap attacks defeat them.',
        bodyAr:
            'مع تداول بيانات اعتماد مُسربة، كلمة المرور وحدها لا تكفي. فعّل المصادقة الثنائية عبر تطبيق مصادقة TOTP (أو مفتاح أمان فعلي / Passkey) بدءًا من: البريد الإلكتروني، الخدمات البنكية، التخزين السحابي، ثم الحسابات الاجتماعية. تجنّب رموز SMS متى توفر خيار التطبيق — هجمات تبديل الشريحة تتجاوزها.',
      ));
    }

    // 5 — Security questions.
    if (exposedTypes.contains('Security questions and answers') ||
        exposedTypes.contains('Password hints')) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.high,
        iconKey: 'help',
        effortMinutes: 15,
        titleEn: 'Reset security questions with random fake answers',
        titleAr: 'أعد تعيين أسئلة الأمان بإجابات وهمية عشوائية',
        bodyEn:
            'Your security answers (or password hints) were exposed. On every service that still uses them, replace answers with long random strings stored in your password manager. Real answers (mother\'s maiden name, first school) are OSINT-trivial to find.',
        bodyAr:
            'تم تسريب إجابات أسئلة الأمان (أو تلميحات كلمة المرور). في كل خدمة ما زالت تستخدمها، استبدل الإجابات بسلاسل عشوائية طويلة محفوظة في مدير كلمات المرور. الإجابات الحقيقية (اسم عائلة الأم، أول مدرسة) سهلة الاستنتاج عبر OSINT.',
      ));
    }

    // 6 — Phone exposure.
    if (exposedTypes.contains('Phone numbers') ||
        inputKind == InputKind.phone) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.high,
        iconKey: 'phone',
        effortMinutes: 10,
        titleEn: 'Harden the exposed phone number against SIM-swap & smishing',
        titleAr: 'حصّن رقم الهاتف المُعرّض ضد تبديل الشريحة والتصيد عبر SMS',
        bodyEn:
            'A leaked number invites SIM-swap fraud, smishing and WhatsApp/Telegram impersonation. Set a carrier account PIN/port-out lock, remove the number from public bios, enable WhatsApp two-step verification PIN and Telegram two-step verification, and never read OTP codes to callers.',
        bodyAr:
            'رقم الهاتف المُسرب يعرّضك لاحتيال تبديل الشريحة والتصيد عبر الرسائل وانتحال الشخصية في واتساب وتيليجرام. عيّن رمز PIN لحسابك لدى شركة الاتصالات وقفل نقل الرقم، احذف الرقم من النبذات العامة، فعّل التحقق بخطوتين في واتساب وتيليجرام، ولا تقرأ رموز OTP لأي متصل أبدًا.',
      ));
    }

    // 7 — Public footprint reduction.
    if (foundPlatforms.length >= 5) {
      final sample = foundPlatforms.map((h) => h.platform.name).take(4).join(', ');
      steps.add(RemediationStep(
        priority: RemediationPriority.medium,
        iconKey: 'eyeOff',
        effortMinutes: 40,
        titleEn:
            'Reduce identity correlation across ${foundPlatforms.length} public accounts',
        titleAr:
            'قلّل إمكانية ربط الهوية عبر ${foundPlatforms.length} حسابًا عامًا',
        bodyEn:
            'The same username is registered on $sample and more. Attackers pivot between these profiles to build a pretext (job, city, family, routines). Delete dormant accounts, switch non-essential profiles to a different alias + unique avatar, remove phone/email from public bios, and lock down friend/follower lists.',
        bodyAr:
            'نفس اسم المستخدم مسجل في $sample وغيرها. يتنقل المهاجمون بين هذه الحسابات لبناء سيناريو احتيال (الوظيفة، المدينة، العائلة، الروتين). احذف الحسابات المهجورة، غيّر اسم وصورة الحسابات غير الأساسية، احذف الهاتف والبريد من النبذات العامة، وأغلق قوائم الأصدقاء والمتابعين.',
      ));
    } else if (foundPlatforms.isNotEmpty) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.low,
        iconKey: 'eye',
        effortMinutes: 15,
        titleEn: 'Review privacy settings on discovered accounts',
        titleAr: 'راجع إعدادات الخصوصية في الحسابات المكتشفة',
        bodyEn:
            'A small number of public accounts were found for this username. Verify each one is yours (unrecognized accounts may be impersonation), tighten who can see posts/friends lists, and remove personal details (birthdate, phone, workplace) from public fields.',
        bodyAr:
            'تم العثور على عدد قليل من الحسابات العامة لهذا الاسم. تحقق أن كل حساب يخصك فعلًا (الحسابات غير المعروفة قد تكون انتحالًا)، شدّد من يستطيع رؤية المنشورات وقوائم الأصدقاء، واحذف التفاصيل الشخصية (تاريخ الميلاد، الهاتف، جهة العمل) من الحقول العامة.',
      ));
    }

    // 8 — Address / DOB driven pretexting.
    if (exposedTypes.contains('Physical addresses') ||
        exposedTypes.contains('Dates of birth')) {
      steps.add(const RemediationStep(
        priority: RemediationPriority.medium,
        iconKey: 'mapPin',
        effortMinutes: 20,
        titleEn: 'Expect targeted pretexting — set a family code word',
        titleAr: 'توقّع احتيالًا موجّهًا — ضع كلمة سر عائلية',
        bodyEn:
            'Home address / date of birth exposure powers convincing bank, courier and "relative in trouble" scams. Agree on a verbal code word with close family for emergency requests, verify courier/bank calls by calling official numbers, and request removal from data-broker/people-search sites.',
        bodyAr:
            'تسريب عنوان السكن / تاريخ الميلاد يغذّي عمليات احتيال مقنعة (بنوك، شركات شحن، "قريب في مأزق"). اتفق على كلمة سر شفهية مع العائلة لطلبات الطوارئ، تحقق من اتصالات البنوك والشحن بالاتصال بالأرقام الرسمية، واطلب إزالة بياناتك من مواقع وسطاء البيانات والبحث عن الأشخاص.',
      ));
    }

    // 9 — Baseline hygiene, always useful.
    steps.add(const RemediationStep(
      priority: RemediationPriority.low,
      iconKey: 'checkCircle',
      effortMinutes: 30,
      titleEn: 'Adopt a password manager + breach monitoring routine',
      titleAr: 'اعتمد مدير كلمات مرور وروتينًا لمراقبة التسريبات',
      bodyEn:
          'Store a unique password per account in an audited password manager, keep its master passphrase long and offline-backed-up, and re-run this audit quarterly. Subscribe the email to breach notifications (e.g. haveibeenpwned.com/NotifyMe) so new exposures surface within days, not years.',
      bodyAr:
          'احفظ كلمة مرور فريدة لكل حساب في مدير كلمات مرور موثوق، اجعل عبارته الرئيسية طويلة ومحفوظة نسختها دون اتصال، وأعد تشغيل هذا التدقيق كل ثلاثة أشهر. اشترك في إشعارات التسريب لبريدك (مثل haveibeenpwned.com/NotifyMe) لتظهر التسريبات الجديدة خلال أيام لا سنوات.',
    ));

    steps.sort((a, b) => a.priority.index.compareTo(b.priority.index));
    return steps;
  }
}
