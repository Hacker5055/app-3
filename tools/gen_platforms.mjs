#!/usr/bin/env node
// Footprint Guard — platform code generator.
// Single source of truth: data/platforms.json
// Outputs: lib/data/platforms.dart  +  web_preview/platforms.js
// Usage: node tools/gen_platforms.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const src = JSON.parse(readFileSync('data/platforms.json', 'utf8'));
const platforms = src.platforms;

const dartString = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$') + "'";
const checkEnum = { status: 'PlatformCheckType.status', message_absent: 'PlatformCheckType.messageAbsent', message_present: 'PlatformCheckType.messagePresent' };
const relEnum = { high: 'Reliability.high', medium: 'Reliability.medium', low: 'Reliability.low' };

let Dart = `// GENERATED by tools/gen_platforms.mjs from data/platforms.json — DO NOT EDIT MANUALLY.
// ${platforms.length} platforms. Methodology inspired by WhatsMyName / Holehe existence checks.

/// How an account-existence check is evaluated for a platform.
enum PlatformCheckType { status, messageAbsent, messagePresent }

/// Real-world false-positive risk of the check.
enum Reliability { high, medium, low }

/// A single OSINT username-recon target platform.
class PlatformDef {
  final String name;
  final String category;
  final String urlTemplate;
  final PlatformCheckType checkType;
  final List<String> markers;
  final Reliability reliability;
  final String? note;

  const PlatformDef({
    required this.name,
    required this.category,
    required this.urlTemplate,
    required this.checkType,
    this.markers = const [],
    this.reliability = Reliability.medium,
    this.note,
  });

  String urlFor(String username) =>
      urlTemplate.replaceAll('{u}', Uri.encodeComponent(username));
}

/// The complete platform database (${platforms.length} platforms).
const List<PlatformDef> kPlatforms = [
`;
for (const p of platforms) {
  const markers = p.markers && p.markers.length ? `[${p.markers.map(dartString).join(', ')}]` : '[]';
  Dart += `  PlatformDef(name: ${dartString(p.name)}, category: ${dartString(p.category)}, urlTemplate: ${dartString(p.url)}, checkType: ${checkEnum[p.checkType]}, markers: ${markers}, reliability: ${relEnum[p.reliability]}${p.note ? `, note: ${dartString(p.note)}` : ''}),\n`;
}
Dart += `];\n`;

mkdirSync(dirname('lib/data/platforms.dart'), { recursive: true });
writeFileSync('lib/data/platforms.dart', Dart);

const js = `// GENERATED by tools/gen_platforms.mjs from data/platforms.json — DO NOT EDIT MANUALLY.\nwindow.FG_PLATFORMS = ${JSON.stringify(platforms, null, 1)};\n`;
mkdirSync('web_preview', { recursive: true });
writeFileSync('web_preview/platforms.js', js);

console.log(`Generated lib/data/platforms.dart + web_preview/platforms.js — ${platforms.length} platforms`);
const cats = {};
for (const p of platforms) cats[p.category] = (cats[p.category] || 0) + 1;
console.log('Categories:', cats);
if (platforms.length < 50) { console.error('ERROR: fewer than 50 platforms'); process.exit(1); }
